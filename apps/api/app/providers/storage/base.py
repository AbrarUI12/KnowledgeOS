"""Contract: object storage (T1.0). Implementations: S3ObjectStore (MinIO/B2/R2) +
InMemoryObjectStore
(Codex, T2.2).

Keys are generated by KnowledgeOS, never derived from user filenames (plan §9). Presigned URLs use
the *public* endpoint (reachable by the browser); every other call uses the internal endpoint.
"""

from collections.abc import AsyncIterator
from datetime import datetime
from typing import Protocol, runtime_checkable

from pydantic import BaseModel, ConfigDict


class PresignedUpload(BaseModel):
    model_config = ConfigDict(frozen=True)

    url: str
    method: str = "PUT"
    headers: dict[str, str] = {}  # headers the client must send (e.g. Content-Type)
    expires_at: datetime


class PresignedDownload(BaseModel):
    """A short-lived GET link to one object, issued only after the caller's access check."""

    model_config = ConfigDict(frozen=True)

    url: str
    expires_at: datetime


class ObjectInfo(BaseModel):
    model_config = ConfigDict(frozen=True)

    bucket: str
    key: str
    size_bytes: int
    content_type: str | None = None
    etag: str | None = None
    last_modified: datetime | None = None


class ObjectStoreError(RuntimeError):
    """Operational storage failure (retryable unless stated otherwise)."""


@runtime_checkable
class ObjectStore(Protocol):
    async def presign_put(
        self, bucket: str, key: str, *, content_type: str, expires_in_seconds: int = 900
    ) -> PresignedUpload: ...

    async def presign_get(
        self, bucket: str, key: str, *, expires_in_seconds: int = 300, filename: str | None = None
    ) -> PresignedDownload:
        """Short-lived download link on the public endpoint (T5.4 source viewer), issued only after
        the caller's access check. `filename` sets `Content-Disposition: inline; filename=...`;
        it is never part of the key."""
        ...

    async def head(self, bucket: str, key: str) -> ObjectInfo | None:
        """Metadata, or None if the object doesn't exist."""
        ...

    def get_stream(
        self, bucket: str, key: str, *, chunk_size: int = 1024 * 1024
    ) -> AsyncIterator[bytes]:
        """Stream the object's bytes (async iterator)."""
        ...

    async def get_bytes(self, bucket: str, key: str, *, max_bytes: int) -> bytes:
        """Read the whole object; raises ObjectStoreError if larger than `max_bytes`."""
        ...

    async def put(self, bucket: str, key: str, data: bytes, *, content_type: str) -> ObjectInfo: ...

    async def copy(self, src_bucket: str, src_key: str, dst_bucket: str, dst_key: str) -> None: ...

    async def delete(self, bucket: str, key: str) -> None:
        """Idempotent: deleting a missing object is not an error."""
        ...

    async def exists(self, bucket: str, key: str) -> bool: ...
