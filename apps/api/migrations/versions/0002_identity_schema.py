def _create_triggers() -> None:
    # Audit events are append-only. UPDATE is always rejected. DELETE is only allowed when the
    # transaction explicitly opts in (retention purges, Session 49): SET LOCAL app.audit_purge = 'on'.
    op.execute(
        """
        CREATE FUNCTION kos_audit_events_append_only() RETURNS trigger
        LANGUAGE plpgsql AS $$
        BEGIN
          IF TG_OP = 'DELETE' AND current_setting('app.audit_purge', true) = 'on' THEN
            RETURN OLD;
          END IF;
          RAISE EXCEPTION 'audit_events is append-only (% rejected)', TG_OP
            USING ERRCODE = 'insufficient_privilege';
        END $$;
        """
    )
    op.execute(
        """
        CREATE TRIGGER trg_audit_events_append_only
        BEFORE UPDATE OR DELETE ON audit_events
        FOR EACH ROW EXECUTE FUNCTION kos_audit_events_append_only();
        """
    )

    # A membership/invitation may only reference a system role or a role of the same org.
    op.execute(
        """
        CREATE FUNCTION kos_check_role_scope() RETURNS trigger
        LANGUAGE plpgsql AS $$
        DECLARE role_org uuid;
        BEGIN
          SELECT organization_id INTO role_org FROM roles WHERE id = NEW.role_id;
          IF role_org IS NOT NULL AND role_org <> NEW.organization_id THEN
            RAISE EXCEPTION 'role % belongs to another organization', NEW.role_id
              USING ERRCODE = 'foreign_key_violation';
          END IF;
          RETURN NEW;
        END $$;
        """
    )
    for table in ("memberships", "invitations"):
        op.execute(
            f"""
            CREATE TRIGGER trg_{table}_role_scope
            BEFORE INSERT OR UPDATE OF role_id, organization_id ON {table}
            FOR EACH ROW EXECUTE FUNCTION kos_check_role_scope();
            """
        )


